/**
 * Refreshes App Store ratings for every project with an App Store link and
 * writes src/data/storeRatings.ts. Runs before each build (npm "prebuild").
 *
 * Source: Apple's public iTunes lookup API, US storefront, where most of the
 * ratings are. Ratings with fewer than MIN_COUNT reviews are left out.
 *
 * It never fails the build: if Apple can't be reached, or rate-limits a
 * request, the previously saved rating for that app is kept.
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PROJECTS = resolve(ROOT, "src/data/projects.ts");
const OUT = resolve(ROOT, "src/data/storeRatings.ts");
const COUNTRY = "us";
const MIN_COUNT = 5;

/** project id -> App Store numeric id, read from the links in projects.ts */
async function appStoreIds() {
  const src = await readFile(PROJECTS, "utf8");
  const ids = {};
  for (const block of src.split(/\n  \{\n/).slice(1)) {
    const id = block.match(/^ {4}id: "([a-z0-9-]+)"/)?.[1];
    const apple = block.match(/apps\.apple\.com\/[^"]*\/id(\d+)/)?.[1];
    if (id && apple) ids[id] = apple;
  }
  return ids;
}

async function previous() {
  try {
    const src = await readFile(OUT, "utf8");
    return JSON.parse(src.match(/= (\{[\s\S]*\});/)[1]);
  } catch {
    return {};
  }
}

async function lookup(appleId) {
  const res = await fetch(`https://itunes.apple.com/lookup?id=${appleId}&country=${COUNTRY}`, {
    signal: AbortSignal.timeout(15_000),
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const app = (await res.json()).results?.[0];
  if (!app) return null; // not listed in this storefront
  return { rating: Math.round(app.averageUserRating * 10) / 10, count: app.userRatingCount ?? 0 };
}

async function main() {
  const ids = await appStoreIds();
  const prev = await previous();
  const next = {};
  for (const [project, appleId] of Object.entries(ids)) {
    try {
      const r = await lookup(appleId);
      if (r && r.count >= MIN_COUNT) next[project] = r;
      console.log(`  ${project}: ${r ? `${r.rating} (${r.count})` : "not listed"}`);
    } catch (err) {
      if (prev[project]) next[project] = prev[project];
      console.warn(`  ${project}: lookup failed (${err.message}), kept ${prev[project] ? "previous value" : "nothing"}`);
    }
  }
  const body =
    `// Generated by scripts/fetch-store-ratings.mjs from Apple's public lookup API (${COUNTRY.toUpperCase()} App Store).\n` +
    `// Refreshed before every build; edit the script, not this file.\n\n` +
    `export interface StoreRating {\n  rating: number;\n  count: number;\n}\n\n` +
    `export const storeRatings: Record<string, StoreRating> = ${JSON.stringify(next, null, 2)};\n`;
  await writeFile(OUT, body);
  console.log(`✓ src/data/storeRatings.ts (${Object.keys(next).length} rated apps)`);
}

main().catch((err) => console.warn("store ratings skipped:", err.message));
